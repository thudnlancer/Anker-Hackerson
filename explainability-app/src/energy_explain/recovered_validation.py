"""Explicit validation inputs for recovered strategy code. These are not historical telemetry."""
from __future__ import annotations

import numpy as np
import pandas as pd

from .recovered_provider import MODEL_VERSION, SOURCE_SHA256, verify_source
from .schemas import DecisionIn
from .store import Store
from .strategy_vendor.rolling_original import optimize_window


def validation_records() -> list[DecisionIn]:
    verify_source()
    records = []
    for site,n,soc,contract in (("model-4-step",4,20,"battery"),("model-24-step",24,60,"sop"),("model-96-step",96,45,"sop")):
        dt = .25 if n == 96 else 1
        hours = np.arange(n)*dt
        if n == 4:
            pv,load,buy = np.zeros(n),np.array([1,3,3,1]),np.array([.1,.35,.4,.15])
        elif n == 96:
            # Keep the smoke test tractable; a 96-step solve is not a worst-case latency claim.
            pv,load,buy = np.full(n,.4),np.full(n,1.0),np.full(n,.2)
        else:
            pv = np.maximum(0,5*np.sin((hours-6)/12*np.pi))
            load = 1.2+.4*(np.cos(hours/24*2*np.pi)**2)
            buy = np.where(hours<6,-.05,np.where((hours>=17)&(hours<21),.4,.18))
        sell = np.full(n,.04)
        s = {"device_time":"2026-10-13T00:00:00Z","observed_at":"2026-10-13T00:00:00Z",
            "soc_percent":soc,"pv_kw":float(pv[0]),"load_kw":float(load[0]),"capacity_kwh":14,
            "max_charge_kw":5,"max_discharge_kw":5,"step_hours":dt,"soc_min_percent":0,"soc_max_percent":100,
            "charge_efficiency":.95,"discharge_efficiency":1,"pv_forecast_kw":pv.tolist(),"load_forecast_kw":load.tolist(),
            "import_eur_kwh":buy.tolist(),"export_eur_kwh":sell.tolist(),"terminal_eur_kwh":.1,"degradation_eur_kwh":.002,
            "sources":dict.fromkeys(("pv","load","pv_forecast","load_forecast"),"synthetic"),
            "history_mode":"none","forecast_status":"ready"}
        times = pd.Series(pd.date_range(s["device_time"],periods=n,freq=pd.Timedelta(hours=dt)))
        # Candidate generated by the preserved, unmodified original optimizer.
        original = optimize_window(times,pv*1000,load*1000,buy,sell,soc,capacity_kwh=14,max_power_w=5000,
            charge_efficiency=.95,terminal_price=.1,degradation_cost_eur_kwh=.002,soc_min=0,soc_max=100,
            step_hours=dt,solver="milp",time_limit_seconds=10,command_contract=contract)
        if original.status != "optimal": raise RuntimeError("original source validation failed: "+original.message)
        frame = original.plan
        values = [frame[k].to_numpy(dtype=float)/1000 for k in ("charge_w","discharge_w","grid_import_w","grid_export_w")]
        charge,discharge,gi,go = values
        first = dict(zip(("charge_kw","discharge_kw","grid_import_kw","grid_export_kw"),(float(x[0]) for x in values)))
        if charge[0] > 1e-6:
            action = {"kind":"charge","power_kw":float(charge[0]),"control_semantics":"battery_charge"}
        elif discharge[0] > 1e-6:
            action = {"kind":"discharge","power_kw":float(go[0]) if contract=="sop" else float(discharge[0]),
                      "control_semantics":"grid_export_target" if contract=="sop" else "external"}
        else:
            action = {"kind":"hold","power_kw":0,"control_semantics":"self_consumption"}
        cost = {"purchase_eur":float(gi@buy*dt),"export_revenue_eur":float(go@sell*dt),
                "degradation_eur":float(np.sum(charge+discharge)*.002*dt),
                "terminal_credit_eur":float(frame["soc_end"].iloc[-1]/100*14*.1),"objective_eur":original.objective}
        records.append(DecisionIn(run_id="recovered-model-validation-v1",site_id=site,decision_id="optimizer-0001",
            source_kind="external",snapshot=s,action=action,model_version=MODEL_VERSION,
            policy_version="recovered-rolling-direct-validation-v1",solver_status=original.status,cost=cost,
            replay_context={"upstream_source_sha256":SOURCE_SHA256,"command_contract":contract,"first_step":first},
            provenance={"origin":"model_validation","input_kind":"synthetic",
                "references":["supplied-rollout:4705","supplied-rollout:5357", "sha256:"+SOURCE_SHA256],
                "note":"实际历史 rolling.py MILP 源码的接入验证；输入均为人工构造，候选由未修改的原求解器生成。没有 HA 写入或官方结算。"}))
    return records


def seed_validation(store: Store) -> list[str]:
    return [store.add_decision(d)["id"] for d in validation_records()]
